#!/usr/bin/env node
/**
 * Generates chatJs.ts, markedJs.ts, and katexJs.ts from source files.
 *
 * When to run:
 *   - After editing a chat*.js runtime module (chat logic)
 *   - After upgrading the `marked` package
 *   CSS (chatCss.ts) does NOT need a rebuild — it's imported directly at runtime.
 *
 * Usage:  pnpm build:webview   (runs: tsx src/components/chat/webview/build.ts)
 */

import { readFileSync, writeFileSync } from 'fs'
import { resolve, dirname } from 'path'
import { fileURLToPath } from 'url'

const __dirname = dirname(fileURLToPath(import.meta.url))

// ── chatJs.ts ─────────────────────────────────────────────────────────────────

const chatCaptureJs = readFileSync(resolve(__dirname, 'chatCapture.js'), 'utf-8')
const chatRenderJs = readFileSync(resolve(__dirname, 'chatRender.js'), 'utf-8')
const chatMarkdownJs = readFileSync(resolve(__dirname, 'chatMarkdown.js'), 'utf-8')
const chatCopyJs = readFileSync(resolve(__dirname, 'chatCopy.js'), 'utf-8')
const chatHooksJs = readFileSync(resolve(__dirname, 'chatHooks.js'), 'utf-8')
const chatVirtualizationJs = readFileSync(resolve(__dirname, 'chatVirtualization.js'), 'utf-8')
const chatMessageRenderingJs = readFileSync(resolve(__dirname, 'chatMessageRendering.js'), 'utf-8')
const chatScrollJs = readFileSync(resolve(__dirname, 'chatScroll.js'), 'utf-8')
const workerCardJs = readFileSync(resolve(__dirname, 'workerCard.js'), 'utf-8')
const chatJs =
  workerCardJs + '\n' +
  chatMessageRenderingJs + '\n' + chatScrollJs + '\n' +
  chatCaptureJs +
  '\n' +
  chatRenderJs +
  '\n' +
  chatMarkdownJs +
  '\n' +
  chatCopyJs +
  '\n' +
  chatHooksJs +
  '\n' +
  chatVirtualizationJs +
  '\n' +
  readFileSync(resolve(__dirname, 'chat.js'), 'utf-8')

writeFileSync(
  resolve(__dirname, 'chatJs.ts'),
  `// Auto-generated by build.ts — do not edit manually.
// Edit the chat*.js runtime modules instead, then run \`pnpm build:webview\`.
export const CHAT_JS: string = ${JSON.stringify(chatJs)};
`,
  'utf-8',
)
console.log('✓ chatJs.ts generated (' + Math.round(chatJs.length / 1024) + 'KB)')

// ── markedJs.ts ───────────────────────────────────────────────────────────────

let markedJs: string | undefined
const candidates = [
  resolve(__dirname, '../../../../../node_modules/marked/lib/marked.umd.js'),
  resolve(__dirname, '../../../../../../node_modules/marked/lib/marked.umd.js'),
]
for (const p of candidates) {
  try { markedJs = readFileSync(p, 'utf-8'); break } catch { /* try next */ }
}
if (!markedJs) {
  console.error('Could not find marked/lib/marked.umd.js')
  process.exit(1)
}

const codeBlockRenderer = `
(function() {
  window._codeBlockCopyStore = window._codeBlockCopyStore || {};
  window._codeBlockCopySeq = window._codeBlockCopySeq || 0;
  function registerCodeBlockCopyText(code) {
    var id = 'cb-' + (++window._codeBlockCopySeq).toString(36);
    window._codeBlockCopyStore[id] = code;
    var keys = Object.keys(window._codeBlockCopyStore);
    while (keys.length > 256) {
      delete window._codeBlockCopyStore[keys.shift()];
    }
    return id;
  }
  var renderer = new marked.Renderer();
  renderer.code = function(src) {
    var code, lang;
    if (typeof src === 'object' && src !== null) {
      code = src.text || '';
      lang = src.lang || '';
    } else {
      code = src || '';
      lang = arguments[1] || '';
    }
    var escaped = code.replace(/&/g,'&amp;').replace(/</g,'&lt;').replace(/>/g,'&gt;').replace(/"/g,'&quot;');
    var langLabel = lang ? '<span class="code-block-lang">' + lang + '</span>' : '<span></span>';
    var copyId = registerCodeBlockCopyText(code);
    return '<div class="code-block-wrap">'
      + '<div class="code-block-header">'
      + langLabel
      + '<button class="code-block-copy" type="button" onclick="window._copyCode(this)" data-code-id="' + copyId + '">Copy</button>'
      + '</div>'
      + '<pre><code>' + escaped + '</code></pre>'
      + '</div>';
  };
  marked.setOptions({ renderer: renderer });
})();
`

writeFileSync(
  resolve(__dirname, 'markedJs.ts'),
  `// Auto-generated by build.ts — do not edit manually.
// Re-run \`pnpm build:webview\` only when upgrading the marked package.
export const MARKED_JS: string = ${JSON.stringify(markedJs + '\n' + codeBlockRenderer)};
`,
  'utf-8',
)
console.log('✓ markedJs.ts generated (' + Math.round(markedJs.length / 1024) + 'KB)')

// ── katexJs.ts ────────────────────────────────────────────────────────────────

let katexJs: string | undefined
const katexCandidates = [
  resolve(__dirname, '../../../../../node_modules/katex/dist/katex.min.js'),
  resolve(__dirname, '../../../../../../node_modules/katex/dist/katex.min.js'),
]
for (const p of katexCandidates) {
  try { katexJs = readFileSync(p, 'utf-8'); break } catch { /* try next */ }
}
if (!katexJs) {
  console.error('Could not find katex/dist/katex.min.js')
  process.exit(1)
}

writeFileSync(
  resolve(__dirname, 'katexJs.ts'),
  `// Auto-generated by build.ts — do not edit manually.
// Re-run \`pnpm build:webview\` after upgrading the katex package.
export const KATEX_JS: string = ${JSON.stringify(katexJs)};
`,
  'utf-8',
)
console.log('✓ katexJs.ts generated (' + Math.round(katexJs.length / 1024) + 'KB)')
