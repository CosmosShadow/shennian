type ManagerModelId = 'codex' | 'claude'
type ManagerSubstrate = Exclude<import('@shennian/wire').AgentType, 'manager' | 'pi' | 'openclaw'>

function normalizeManagerModel(modelId?: string): ManagerModelId {
  return modelId === 'claude' ? 'claude' : 'codex'
}

function safeSessionDirName(sessionId: string): string {
  return sessionId.replace(/[^a-zA-Z0-9_.-]/g, '_')
}

function readProjectAgentsMd(workDir: string): string {
  const agentsPath = path.join(workDir, 'AGENTS.md')
  try {
    return fs.readFileSync(agentsPath, 'utf8').trim()
  } catch {
    return ''
  }
}

function managerInstructionsPath(workDir: string, sessionId: string): string {
  return path.join(workDir, '.shennian', 'runtime', 'manager', safeSessionDirName(sessionId), 'instructions.md')
}

function buildStableManagerInstructions(workDir: string, managerSessionId: string): string {
  const projectInstructions = readProjectAgentsMd(workDir)
  const managerRuntime = getManagerRuntimeService()
  const channelInstructions = managerRuntime?.getManagerExternalChannelSystemPrompt(managerSessionId) ?? ''
  const workerDefaults = typeof managerRuntime?.getManagerWorkerDefaults === 'function'
    ? managerRuntime.getManagerWorkerDefaults(managerSessionId)
    : undefined
  const workerDefaultInstructions = workerDefaults?.agentType
    ? `默认 worker Agent：${workerDefaults.agentType}${workerDefaults.modelId ? `\n默认 worker 模型：${workerDefaults.modelId}` : ''}。除非用户明确要求或任务明显需要其他 Agent/模型，创建 worker 时优先使用这个默认组合。`
    : ''
  const sections = [
    '# Shennian Manager Instructions',
    'This file is generated by Shennian for a Manager Agent substrate session. Do not edit it by hand.',
    projectInstructions
      ? `## Project Instructions\n\n${projectInstructions}`
      : '',
    `## Manager Instructions\n\n${MANAGER_SYSTEM_PROMPT}`,
    workerDefaultInstructions
      ? `## Worker Defaults\n\n${workerDefaultInstructions}`
      : '',
    channelInstructions
      ? `## External Message Channel Instructions\n\n${channelInstructions}`
      : '',
    PLATFORM_OUTPUT_INSTRUCTIONS,
  ].filter(Boolean)
  return `${sections.join('\n\n')}\n`
}

function ensureManagerInstructionsFile(workDir: string, sessionId: string): string {
  const filePath = managerInstructionsPath(workDir, sessionId)
  const content = buildStableManagerInstructions(workDir, sessionId)
  fs.mkdirSync(path.dirname(filePath), { recursive: true })
  try {
    if (fs.readFileSync(filePath, 'utf8') === content) return filePath
  } catch {
    // Write the generated instruction file below.
  }
  fs.writeFileSync(filePath, content)
  return filePath
}

/** Decorates a real provider Adapter with Manager session capabilities. New
 * sessions use this class and keep their real agentType/modelId. */
export class ManagerModeAdapter extends AgentAdapter {
  readonly type
  override get recoveryCapabilities() { return this.inner.recoveryCapabilities }
  private sessionId = ''
  private workDir = ''
  private agentSessionId: string | null = null
  private configured: {
    sessionId?: string
    externalChannel?: ExternalChannelSessionStatus | null
    env?: NodeJS.ProcessEnv
    managedAgentPolicy?: CompiledManagedAgentPolicy | null
  } = {}

  constructor(
    private readonly inner: AgentAdapter,
    private readonly substrate: ManagerSubstrate,
  ) {
    super()
    this.type = inner.type
    inner.on('agentEvent', (event) => {
      if (event.agentSessionId) this.agentSessionId = event.agentSessionId
      this.emit('agentEvent', { ...event, source: event.source ?? substrate })
    })
    inner.on('nativeSession', (provider, id) => this.emit('nativeSession', provider, id))
    inner.on('error', (error) => this.emit('error', error))
  }

  configure(options: {
    sessionId?: string
    externalChannel?: ExternalChannelSessionStatus | null
    env?: NodeJS.ProcessEnv
    managedAgentPolicy?: CompiledManagedAgentPolicy | null
  }): void {
    this.configured = options
    if (options.sessionId) {
      getManagerRuntimeService()?.setManagedAgentPolicy(
        options.sessionId,
        options.managedAgentPolicy ?? null,
      )
    }
    this.applyEnvironment()
  }

  async start(
    sessionId: string,
    workDir: string,
    agentSessionId?: string | null,
    options?: import('./adapter.js').AgentStartOptions,
  ): Promise<void> {
    this.sessionId = sessionId
    this.workDir = workDir
    this.agentSessionId = agentSessionId ?? null
    this.applyEnvironment()
    await this.inner.start(sessionId, workDir, agentSessionId, options)
    getManagerRuntimeService()?.registerManager({
      sessionId, agentSessionId: this.agentSessionId, workDir, modelId: this.substrate,
      agentType: this.type, status: 'idle',
    })
    getManagerRuntimeService()?.bindManagerAdapterEvents(sessionId, this.inner)
  }

  async send(
    text: string,
    modelId?: string,
    reasoningEffort?: string,
    attachments?: ChatAttachmentMeta[],
    agentSystemPrompt?: string | null,
    context?: AgentSendContext,
  ): Promise<void | AgentSendResult> {
    getManagerRuntimeService()?.registerManager({
      sessionId: this.sessionId, agentSessionId: this.agentSessionId, workDir: this.workDir,
      modelId: this.substrate, agentType: this.type,
      providerModelId: modelId ?? null, status: 'running',
    })
    await getManagerRuntimeService()?.ready()
    this.applyEnvironment()
    const managerInstructions = buildStableManagerInstructions(this.workDir, this.sessionId)
    const combined = combineManagerInstructions(managerInstructions, agentSystemPrompt)
    return this.inner.send(
      buildManagerPrompt(text), modelId, reasoningEffort, attachments, combined, context,
    )
  }

  async resume(agentSessionId: string): Promise<void> {
    this.agentSessionId = agentSessionId
    await this.inner.resume(agentSessionId)
  }

  async stop(): Promise<void> {
    getManagerRuntimeService()?.setManagedAgentPolicy(this.sessionId, null)
    await this.inner.stop()
  }

  getStatus() { return this.inner.getStatus?.() ?? Promise.resolve({ active: false }) }

  setTitle(agentSessionId: string, title: string, workDir?: string) {
    return this.inner.setTitle?.(agentSessionId, title, workDir) ?? Promise.resolve()
  }

  private applyEnvironment(): void {
    const managerEnv = this.sessionId
      ? getManagerRuntimeService()?.getInjectedEnv(this.sessionId, this.agentSessionId, this.workDir, this.substrate) ?? {}
      : {}
    this.inner.configure?.({
      ...this.configured,
      sessionId: this.configured.sessionId ?? this.sessionId,
      env: { ...(this.configured.env ?? {}), ...managerEnv },
      managedAgentPolicy: this.configured.managedAgentPolicy ?? null,
    })
  }
}

export function combineManagerInstructions(managerInstructions: string, systemPrompt?: string | null): string {
  const prompt = systemPrompt?.trim() ?? ''
  if (!prompt) return managerInstructions
  const roomMarkers = ['[智能体私有系统提示词]', '[智能体身份]']
  const index = roomMarkers
    .map((marker) => prompt.indexOf(marker))
    .filter((position) => position >= 0)
    .sort((a, b) => a - b)[0] ?? -1
  if (prompt.startsWith('[神念受管会话规则]') && index >= 0) {
    return `${prompt.slice(0, index)}[会话模式]\n${managerInstructions.trim()}\n\n${prompt.slice(index)}`
  }
  return `${managerInstructions.trim()}\n\n${prompt}`
}

export class ManagerAdapter extends AgentAdapter {
  readonly type = 'manager' as const
  override get recoveryCapabilities() {
    return this.inner?.recoveryCapabilities ?? {
      inspectTerminal: false,
      reattachRun: false,
      resumeRun: false,
      resumeSession: true,
    }
  }
  private inner: AgentAdapter | null = null
  private sessionId = ''
  private workDir = ''
  private agentSessionId: string | null = null
  private modelId: ManagerModelId = 'codex'
  private startOptions?: import('./adapter.js').AgentStartOptions

  async start(sessionId: string, workDir: string, agentSessionId?: string | null, options?: import('./adapter.js').AgentStartOptions): Promise<void> {
    this.startOptions = options
    this.sessionId = sessionId
    this.workDir = workDir
    this.agentSessionId = agentSessionId ?? null
    getManagerRuntimeService()?.registerManager({
      sessionId,
      agentSessionId: this.agentSessionId,
      workDir,
      modelId: this.modelId,
      agentType: 'manager',
      status: 'idle',
    })
  }

  async send(text: string, modelId?: string): Promise<void> {
    const nextModel = normalizeManagerModel(modelId)
    if (!this.inner || nextModel !== this.modelId) {
      await this.inner?.stop().catch(() => {})
      this.inner?.removeAllListeners()
      this.modelId = nextModel
      const instructionsFile = ensureManagerInstructionsFile(this.workDir, this.sessionId)
      const systemPrompt = buildStableManagerInstructions(this.workDir, this.sessionId)
      this.inner = nextModel === 'claude'
        ? new ClaudeAdapter({ systemPrompt, hidden: true })
        : new CodexAdapter({ modelInstructionsFile: instructionsFile, hidden: true })
      this.bindInner(this.inner)
      await this.inner.start(this.sessionId, this.workDir, this.agentSessionId, this.startOptions)
      getManagerRuntimeService()?.bindManagerAdapterEvents(this.sessionId, this.inner)
    }

    getManagerRuntimeService()?.registerManager({
      sessionId: this.sessionId,
      agentSessionId: this.agentSessionId,
      workDir: this.workDir,
      modelId: this.modelId,
      agentType: 'manager',
      status: 'running',
    })
    await getManagerRuntimeService()?.ready()
    await this.withManagerEnv(() => this.inner!.send(buildManagerPrompt(text)))
  }

  async resume(agentSessionId: string): Promise<void> {
    this.agentSessionId = agentSessionId
    if (this.inner) await this.inner.resume(agentSessionId)
  }

  async stop(): Promise<void> {
    await this.inner?.stop()
  }

  private bindInner(inner: AgentAdapter): void {
    inner.on('agentEvent', (event) => {
      if (event.agentSessionId) this.agentSessionId = event.agentSessionId
      this.emit('agentEvent', this.wrapEvent(event))
    })
    inner.on('nativeSession', (provider, id) => this.emit('nativeSession', provider, id))
    inner.on('error', (error) => this.emit('error', error))
  }

  private wrapEvent(event: AgentEvent): AgentEvent {
    return {
      ...event,
      source: event.source ?? this.modelId,
      agentSessionId: event.agentSessionId ?? this.agentSessionId ?? undefined,
    }
  }

  private async withManagerEnv<T>(work: () => Promise<T>): Promise<T> {
    const env = getManagerRuntimeService()?.getInjectedEnv(
      this.sessionId,
      this.agentSessionId,
      this.workDir,
      this.modelId,
    ) ?? {}
    const previous = new Map<string, string | undefined>()
    for (const [key, value] of Object.entries(env)) {
      previous.set(key, process.env[key])
      process.env[key] = value
    }
    try {
      return await work()
    } finally {
      for (const [key, value] of previous) {
        if (value === undefined) delete process.env[key]
        else process.env[key] = value
      }
    }
  }
}

registerAgent('manager', () => new ManagerAdapter())
